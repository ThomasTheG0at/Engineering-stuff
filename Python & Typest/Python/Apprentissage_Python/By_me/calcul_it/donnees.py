def obtenir_ecarts(symbole, index):
    """Calcule les écarts (ES, EI) ou (es, ei) en µm avec gestion des erreurs."""
    position = "".join([c for c in symbole if c.isalpha()])
    qualite_str = "".join([c for c in symbole if c.isdigit()])

    if not position or not qualite_str:
        raise ValueError(f"Symbole invalide : '{symbole}'. Exemple : H7, g6, H13.")

    qualite = int(qualite_str)
    pos_key = position.lower()

    if qualite not in TABLE_IT:
        raise KeyError(f"Qualité IT{qualite} non prise en charge (IT5 à IT16).")

    if pos_key not in ECARTS_FONDAMENTAUX_ARBRE:
        raise KeyError(f"Position '{position}' inconnue.")

    it = TABLE_IT[qualite][index]
    dev = ECARTS_FONDAMENTAUX_ARBRE[pos_key][index]

    if position.islower():
        if pos_key == "js":
            return (+it / 2, -it / 2)
        elif pos_key in ["a", "b", "c", "d", "e", "f", "g", "h"]:
            es = dev
            ei = es - it
            return (es, ei)
        else:
            ei = dev
            es = ei + it
            return (es, ei)
    else:
        if pos_key == "js":
            return (+it / 2, -it / 2)
        elif pos_key in ["a", "b", "c", "d", "e", "f", "g", "h"]:
            EI = -dev
            ES = EI + it
            return (ES, EI)
        else:
            ES = -dev
            EI = ES - it
            return (ES, EI)